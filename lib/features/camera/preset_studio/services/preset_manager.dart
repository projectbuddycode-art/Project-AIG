  CameraPreset getPreset(String id) {
    return builtInPresets.firstWhere(
      (preset) => preset.id == id,
      orElse: () => builtInPresets.first,
    );
  }

  CameraPreset duplicatePreset(CameraPreset preset, {String? nameOverride}) {
    final baseName = nameOverride ?? '${preset.name} Copy';
    return preset.copyWith(
      id: '${preset.id}-copy-${DateTime.now().millisecondsSinceEpoch}',
      name: baseName,
      isCustom: true,
    );
  }

  List<CameraPreset> removePreset(List<CameraPreset> presets, String id) {
    return presets.where((preset) => preset.id != id).toList();
  }
